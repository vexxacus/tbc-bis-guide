#!/usr/bin/env node
/**
 * Build js/wowhead-guide-data.js from scraped Wowhead BiS guide data.
 * 
 * Maps Wowhead spec names → App spec names, normalises slot names,
 * and outputs a compact JS file that can be loaded via <script> tag.
 *
 * Usage: node build-guide-data.js
 */

const fs = require('fs');
const path = require('path');

const RAW_FILE = path.join(__dirname, 'scraper/output/wowhead-bis-raw.json');
const OUT_FILE = path.join(__dirname, 'js/wowhead-guide-data.js');

const raw = JSON.parse(fs.readFileSync(RAW_FILE, 'utf8'));

// Wowhead spec name → App spec name mapping
const WOWHEAD_TO_APP_SPEC = {
    'Druid|Feral DPS':  'Druid|Cat',
    'Druid|Feral Tank': 'Druid|Bear',
    'Priest|Holy/Disc': 'Priest|Discipline',
    'Rogue|Rogue':      'Rogue|Combat',       // Wowhead has single "Rogue" guide
};

// Rogue guide applies to all rogue specs
const ROGUE_SPECS = ['Combat', 'Assassination', 'Subtlety'];

// Normalise slot names to match app convention
function normaliseSlot(slot) {
    if (slot === 'Helm')     return 'Head';
    if (slot === 'Two-Hand') return 'Two Hand';
    if (slot === 'Weapon')   return 'Main Hand';
    return slot;
}

// Build output: { phases: { 1: { "Warrior|Fury": { slots: { "Head": [{itemId, name}], ... } } } } }
const output = { phases: {} };

for (const [key, specData] of Object.entries(raw)) {
    const phase = specData.phase;
    const wowheadKey = `${specData.class}|${specData.spec}`;
    
    // Map to app spec name(s)
    let appKeys;
    if (wowheadKey === 'Rogue|Rogue') {
        appKeys = ROGUE_SPECS.map(s => `Rogue|${s}`);
    } else {
        appKeys = [WOWHEAD_TO_APP_SPEC[wowheadKey] || wowheadKey];
    }

    // Also map Priest|Holy/Disc → Priest|Holy AND Priest|Discipline
    if (wowheadKey === 'Priest|Holy/Disc') {
        appKeys = ['Priest|Holy', 'Priest|Discipline'];
    }

    const slots = {};
    for (const slotData of specData.slots) {
        const slot = normaliseSlot(slotData.slot);
        if (!slots[slot]) slots[slot] = [];
        
        for (const item of slotData.items) {
            if (!item.itemId) continue;
            // Dedupe within slot
            if (slots[slot].some(i => i.id === item.itemId)) continue;
            slots[slot].push({
                id: item.itemId,
                n: item.itemName,
                r: item.rank || 'Option',  // Original Wowhead rank (BiS, Option, Alternative, etc.)
            });
        }
    }

    if (!output.phases[phase]) output.phases[phase] = {};
    for (const appKey of appKeys) {
        output.phases[phase][appKey] = { slots };
    }
}

// Count stats
let specCount = 0, itemCount = 0;
for (const phase of Object.values(output.phases)) {
    for (const spec of Object.values(phase)) {
        specCount++;
        for (const items of Object.values(spec.slots)) {
            itemCount += items.length;
        }
    }
}

// Write JS file
const js = `// Auto-generated by build-guide-data.js — DO NOT EDIT
// Wowhead BiS guide data: ${specCount} specs, ${itemCount} items
// Source: scraper/output/wowhead-bis-raw.json
const GUIDE_DATA = ${JSON.stringify(output)};
`;

fs.writeFileSync(OUT_FILE, js, 'utf8');
console.log(`✅ Written ${OUT_FILE}`);
console.log(`   ${specCount} spec/phase combos, ${itemCount} total items`);
console.log(`   Phases: ${Object.keys(output.phases).sort().join(', ')}`);
